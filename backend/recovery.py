def guess_type(text: str) -> str:
    """Which situation a sentence describes (for the chatbot). Order matters: the more specific
    and more urgent situations first."""
    import re
    t = text.lower()
    if re.search(r"anydesk|teamviewer|quicksupport|screen[- ]?shar|remote (access|app|control)|installed .*app|install(ed)? (an? )?app", t):
        return "remote_app"
    if re.search(r"arrest|police|cbi|customs|warrant|parcel|court|income tax", t):
        return "digital_arrest"
    if re.search(r"invest|trading|stock|crypto|demat|tips?|group|returns?|profit|forex", t):
        return "invest"
    if re.search(r"\botp\b|\bpin\b|cvv|password|code", t):
        return "shared_code"
    if re.search(r"link|clicked|website|form|kyc update|filled", t):
        return "link_clicked"
    return "upi_card"


def when_label(mins: int, hi: bool = False) -> str:
    """How soon a step matters, in words."""
    if mins <= 0:
        return "अभी" if hi else "now"
    if mins < 60:
        return f"{mins} मिनट में" if hi else f"within {mins} minutes"
    if mins == 60:
        return "1 घंटे में" if hi else "within 1 hour"
    if mins <= 1440:
        return "24 घंटे में" if hi else "within 24 hours"
    if mins <= 4320:
        return "3 कामकाजी दिनों में" if hi else "within 3 working days"
    return "अगले 30 दिन" if hi else "over the next 30 days"
