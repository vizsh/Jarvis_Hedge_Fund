def types(lang: str = "en") -> list[dict[str, str]]:
    return [{"id": k, "label": v["hi" if lang == "hi" else "en"]} for k, v in TYPES.items()]


def plan(kind: str, lang: str = "en") -> dict[str, Any]:
    """The ordered steps for what happened. `mins` is how long the step stays most useful."""
    if kind not in PLAN:
        kind = "upi_card"
    hi = lang == "hi"
    steps = []
    for i, sid in enumerate(PLAN[kind]):
        s = STEPS[sid]
        title, detail = s["hi" if hi else "en"]
        steps.append({"id": sid, "n": i + 1, "title": title, "detail": detail, "mins": s["mins"]})
    return {"type": kind, "label": TYPES[kind]["hi" if hi else "en"], "steps": steps, "lang": lang,
            "helpline": "1930", "portal": "cybercrime.gov.in"}


def _val(x: Any, placeholder: str) -> str:
    x = ("" if x is None else str(x)).strip()
    return x or placeholder


